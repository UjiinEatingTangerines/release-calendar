import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, stat, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { serve } from '@hono/node-server';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { Runtime } from '../dist/runtime.js';
import { createApp } from '../dist/server.js';
const dir = await mkdtemp(join(tmpdir(), 'release-settings-qa-'));
let server, browserServer, browser;
const errors = [], scenarios = [];
try {
  const options = { settingsPath: join(dir, 'connections.json'), dataDir: join(dir, 'data') };
  const runtime = await Runtime.create(options);
  server = serve({ fetch: createApp(runtime, async () => ({ jira: { ok: true, code: 'READ_ACCESS_CONFIRMED' }, github: { ok: true, code: 'READ_ACCESS_CONFIRMED' } })).fetch, hostname: '127.0.0.1', port: 0 });
  if (!server.listening) await new Promise(resolve => server.once('listening', resolve));
  const address = `http://127.0.0.1:${server.address().port}`;
  browserServer = await chromium.launchServer({ channel: process.env.QA_BROWSER_CHANNEL ?? 'chrome', headless: true });
  browser = await chromium.connect(browserServer.wsEndpoint());
  const context = await browser.newContext({ viewport: { width: 1120, height: 900 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  // Provider requests are tested separately; never send fictional credentials to a live service.
  await page.route('**/api/refresh?**', route => route.fulfill({ json: { warnings: [] } }));
  await page.goto(`${address}/settings.html`);
  await page.getByRole('button', { name: '연결 확인', exact: true }).waitFor();
  await page.locator('#connection-name').fill('Fictional Orbit');
  await page.locator('#jira-site').fill('fictional-orbit.atlassian.net');
  await page.locator('#jira-project').fill('ORBIT');
  await page.getByRole('button', { name: '연결 확인', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '이메일과 API 토큰' }).waitFor();
  scenarios.push('Missing credential error is readable and preserves the draft');
  await page.locator('#jira-email').fill('fictional@example.com');
  await page.locator('#jira-token').fill('fictional-jira-secret');
  await page.locator('#github-repos').fill('https://github.com/fictional/orbit');
  await page.locator('#github-token').fill('fictional-github-secret');
  await page.getByRole('button', { name: '연결 확인', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '조회 연결 확인' }).waitFor();
  await page.getByRole('button', { name: '저장하고 동기화', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '완료했습니다' }).waitFor();
  assert.equal(await page.locator('#jira-token').inputValue(), '');
  assert.equal(await page.locator('#github-token').inputValue(), '');
  const view = await (await fetch(`${address}/api/settings`)).json();
  assert.ok(!JSON.stringify(view).includes('fictional-jira-secret'));
  assert.equal((await stat(options.settingsPath)).mode & 0o777, 0o600);
  assert.equal((await Runtime.create(options)).config.projects[0].name, 'Fictional Orbit');
  scenarios.push('Form check/save; private atomic persistence; restart sharing; credentials never returned');
  await page.getByRole('button', { name: '저장하고 동기화', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '완료했습니다' }).waitFor();
  assert.ok((await readFile(options.settingsPath, 'utf8')).includes('fictional-jira-secret'));
  scenarios.push('Blank credential edits preserve saved secrets');
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/settings-desktop.png', fullPage: true });
  assert.deepEqual((await new AxeBuilder({ page }).analyze()).violations, []);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/settings-mobile.png', fullPage: true });
  assert.deepEqual((await new AxeBuilder({ page }).analyze()).violations, []);
  scenarios.push('Desktop/mobile: no horizontal overflow; zero axe violations');
  page.on('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '연결 해제', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '해제했습니다' }).waitFor();
  assert.equal((await Runtime.create(options)).demo, true);
  assert.ok(!(await readFile(options.settingsPath, 'utf8')).includes('fictional-jira-secret'));
  scenarios.push('Confirmed local removal clears managed secrets and restores demo');
  assert.deepEqual(errors, []);
  const report = { verdict: 'PASS', scenarios, liveProviderAuthentication: 'not tested; probe and refresh responses are fixtures' };
  await writeFile('artifacts/settings-qa.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  if (browser) await browser.close();
  if (browserServer) await browserServer.close();
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  await rm(dir, { recursive: true, force: true });
}
